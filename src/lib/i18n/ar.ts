/** "منذ ساعة" / "منذ ساعتين" / "منذ ٥ ساعات" / "منذ ١٢ ساعة". */
function since(n: number, forms: { one: string; two: string; few: string; many: string }): string {
  return n === 1 || n === 2 ? `منذ ${plural(n, forms)}` : `منذ ${num(n)} ${plural(n, forms)}`;
}

/** "يوم واحد" / "يومان" / "٥ أيام" / "١٢ يوماً": a count with its noun. */
function counted(n: number, forms: { one: string; two: string; few: string; many: string }): string {
  return n === 1 || n === 2 ? plural(n, forms) : `${num(n)} ${plural(n, forms)}`;
}

