/** "يوم واحد" / "يومان" / "٥ أيام" / "١٢ يوماً". */
function days(n: number): string {
  const forms = { one: "يوم واحد", two: "يومان", few: "أيام", many: "يوماً" };
  return n === 1 || n === 2 ? plural(n, forms) : `${num(n)} ${plural(n, forms)}`;
}

